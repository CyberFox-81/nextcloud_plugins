# Build {{NAME}} for the browser, with the embedding bridge from patches/, into web/.
#
# Usage: scripts/build-{{ID}}-web.sh [{{ID_UPPER}}_CHECKOUT]
#
#   {{ID_UPPER}}_CHECKOUT  an existing clone of github.com/storytold/{{ID}}. Without it the
#                       script clones {{ID_UPPER}}_REF into build/{{ID}}.
#
# Needs: Rust with the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown)
# and wasm-bindgen-cli at the version in {{NAME}}'s Cargo.lock
# (cargo install wasm-bindgen-cli --version <x.y.z> --locked). wasm-opt (binaryen) is used
# when installed and shrinks the download.
#
# Environment:
#   {{ID_UPPER}}_REF  commit or tag to clone (default: the commit the patch was made against)
#   BUILD_STD=1    build the standard library from source (when the wasm32 target can't be
#                  installed through rustup but rust-src is available)
#   FAST=1         skip LTO and use parallel codegen: quicker builds, bigger wasm
#   CRAFT_FONTS_DIR  a clone of storytold/craft-fonts, to embed the shared Japanese fonts
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
{{ID_UPPER}}_REF="${{{ID_UPPER}}_REF:-{{DEFAULT_REF}}}"
SRC="${1:-$APP_DIR/build/{{ID}}}"
PATCH="$APP_DIR/patches/{{ID}}-nextcloud.patch"
OUT="$APP_DIR/web"
TARGET_DIR="${CARGO_TARGET_DIR:-$SRC/target}"

if [ ! -e "$SRC/.git" ]; then
	git clone https://github.com/storytold/{{ID}}.git "$SRC"
	git -C "$SRC" checkout --quiet "${{ID_UPPER}}_REF"
fi

if grep -rq '{{ID}}:ready' "$SRC/apps/{{ID}}-web/src"; then
	echo "bridge patch already applied"
else
	git -C "$SRC" apply "$PATCH"
fi

cargo_args=(build --profile {{CARGO_PROFILE}} -p {{CARGO_PACKAGE}} --target wasm32-unknown-unknown{{CARGO_FEATURES_ARGS}})
if [ "${BUILD_STD:-0}" = "1" ]; then
	export RUSTC_BOOTSTRAP=1
	cargo_args+=(-Zbuild-std=std,panic_abort)
fi
if [ "${FAST:-0}" = "1" ]; then
	export CARGO_PROFILE_{{CARGO_PROFILE_ENV}}_LTO=off CARGO_PROFILE_{{CARGO_PROFILE_ENV}}_CODEGEN_UNITS=16
fi
(cd "$SRC" && CARGO_TARGET_DIR="$TARGET_DIR" cargo "${cargo_args[@]}")

WASM_IN="$TARGET_DIR/wasm32-unknown-unknown/{{CARGO_PROFILE_DIR}}/{{WASM_FILE}}"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
OUT_NAME={{BINDGEN_OUT_NAME}}
wasm-bindgen --target web{{BINDGEN_FLAGS}} --no-typescript --out-dir "$STAGE" --out-name "$OUT_NAME" "$WASM_IN"

if command -v wasm-opt >/dev/null; then
	wasm-opt {{WASM_OPT_LEVEL}} --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
		--enable-mutable-globals --enable-reference-types --enable-multivalue{{WASM_OPT_FLAGS}} \
		"$STAGE/${OUT_NAME}_bg.wasm" -o "$STAGE/${OUT_NAME}_bg.opt.wasm"
	mv "$STAGE/${OUT_NAME}_bg.opt.wasm" "$STAGE/${OUT_NAME}_bg.wasm"
else
	echo "note: wasm-opt not found; the wasm is not size-optimized"
fi

mkdir -p "$OUT"
hash() { sha256sum "$1" | cut -c1-16; }
{{LAYOUT_SH}}cp "$STAGE/$OUT_NAME.js" "$DEST/$JS_NAME"
cp "$STAGE/${OUT_NAME}_bg.wasm" "$DEST/$WASM_NAME"
# JavaScript the Rust code brings along (`#[wasm_bindgen(module = …)]`), imported by the glue.
rm -rf "$DEST/snippets"
if [ -d "$STAGE/snippets" ]; then cp -R "$STAGE/snippets" "$DEST/snippets"; fi
{{EXTRA_ASSETS_SH}}
# {{NAME}}'s licenses and the attributions for the fonts and assets compiled into it.
for f in LICENSE-MIT LICENSE-APACHE NOTICE ATTRIBUTION.md ASSETS.md; do
	if [ -f "$SRC/$f" ]; then cp "$SRC/$f" "$OUT/{{ID_UPPER}}-$f"; fi
done

cat > "$DEST/boot.js" <<BOOT
/*
 * SPDX-FileCopyrightText: 2026 Britton Couchman <brittondcouchman@gmail.com>
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * Starts {{NAME}} in the editor's iframe (templates/frame.php).
 * Generated by scripts/build-{{ID}}-web.sh from {{NAME}} $(git -C "$SRC" rev-parse --short HEAD).
 */

function reportFailure(error) {
	console.error('{{NAME}} could not start', error)
	if (window.parent !== window) {
		window.parent.postMessage({ type: '{{ID}}:failed', error: String(error?.message ?? error) }, window.location.origin)
	}
}

try {
{{BOOT_BEFORE}}	const app = await import('./$JS_NAME')
	await app.default({ module_or_path: {{BOOT_INIT_ARG}} })
{{BOOT_AFTER}}
} catch (error) {
	reportFailure(error)
}
BOOT

{{STATIC_FRAME_SH}}echo "{{NAME}} web build:"
ls -lh "$OUT"
